"""Download a random sample of images from both datasets and write label manifests.

Usage: python scripts/prepare_data.py --n 100 --seed 42

Writes:
  data/images/mmfood/*.jpg, data/images/nutrition5k/*.jpg   (git-ignored)
  data/manifests/mmfood.jsonl, data/manifests/nutrition5k.jsonl   (committed)

Each manifest line uses the same truth schema as results/clean, so src/scoring.py works on both:
  {"image_id", "dataset", "image_path", "truth": {"dish_name", "cooking_method", "portion_size", "nutrition"}}
"""
import argparse
import csv
import io
import json
import random
import sys
from pathlib import Path

import requests
from PIL import Image

IMAGE_DIR = Path("data/images")
MANIFEST_DIR = Path("data/manifests")
MAX_SIDE = 768  # resize so the longest side is at most this; aspect ratio is preserved

MMFOOD_TYPES = {"Restaurant food", "Home-cooked food", "Processed food", "Snack"}
N5K_BASE = "https://storage.googleapis.com/nutrition5k_dataset/nutrition5k_dataset"
N5K_METADATA = f"{N5K_BASE}/metadata/dish_metadata_cafe1.csv"


def save_image(content: bytes, path: Path):
    img = Image.open(io.BytesIO(content)).convert("RGB")
    img.thumbnail((MAX_SIDE, MAX_SIDE))  # shrinks in place, keeps aspect ratio
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, "JPEG", quality=90)


def download(url: str) -> bytes:
    response = requests.get(url, timeout=15)
    response.raise_for_status()
    return response.content


def as_json(value):
    """MM-Food stores lists/dicts as JSON strings; accept either form."""
    if isinstance(value, str):
        try:
            return json.loads(value)
        except json.JSONDecodeError:
            return None
    return value


# ---------------------------------------------------------------------------
# MM-Food-100K (labels generated by GPT-4o)
# ---------------------------------------------------------------------------
def mmfood_record(row, image_id):
    nutrition = as_json(row["nutritional_profile"])
    if not isinstance(nutrition, dict):
        return None
    return {
        "image_id": image_id,
        "dataset": "mmfood",
        "image_path": f"data/images/mmfood/{image_id}.jpg",
        "truth": {
            "dish_name": row["dish_name"],
            "cooking_method": row["cooking_method"],
            "portion_size": as_json(row["portion_size"]),
            "nutrition": nutrition,
        },
    }


def prepare_mmfood(n, seed):
    from datasets import load_dataset  # heavy import, only needed here

    rows = load_dataset("Codatta/MM-Food-100K", split="train")
    candidates = [i for i, t in enumerate(rows["food_type"]) if t in MMFOOD_TYPES]
    random.Random(seed).shuffle(candidates)

    records = []
    for idx in candidates:
        if len(records) == n:
            break
        row = rows[idx]
        record = mmfood_record(row, f"mmfood_{idx}")
        if record is None:
            continue
        try:
            save_image(download(row["image_url"]), Path(record["image_path"]))
        except Exception as e:  # dead links are common; skip and keep sampling
            print(f"skip mmfood_{idx}: {type(e).__name__}")
            continue
        records.append(record)
    return records


# ---------------------------------------------------------------------------
# Nutrition5k (labels from weighed ingredients)
# ---------------------------------------------------------------------------
def nutrition5k_record(fields):
    """Parse one metadata row: dish_id, calories, mass, fat, carb, protein, then ingredients."""
    try:
        dish_id = fields[0]
        calories, mass, fat, carb, protein = (float(x) for x in fields[1:6])
    except (IndexError, ValueError):
        return None
    if mass <= 0:
        return None
    return {
        "image_id": dish_id,
        "dataset": "nutrition5k",
        "image_path": f"data/images/nutrition5k/{dish_id}.jpg",
        "truth": {
            "dish_name": None,         # Nutrition5k has no dish names
            "cooking_method": None,
            "portion_size": [f"total:{mass:.0f}g"],
            "nutrition": {"calories_kcal": calories, "protein_g": protein,
                          "fat_g": fat, "carbohydrate_g": carb},
        },
    }


def prepare_nutrition5k(n, seed):
    text = download(N5K_METADATA).decode("utf-8")
    candidates = [r for r in (nutrition5k_record(f) for f in csv.reader(io.StringIO(text))) if r]
    random.Random(seed).shuffle(candidates)

    records = []
    for record in candidates:
        if len(records) == n:
            break
        url = f"{N5K_BASE}/imagery/realsense_overhead/{record['image_id']}/rgb.png"
        try:
            save_image(download(url), Path(record["image_path"]))
        except Exception as e:  # not every dish has an overhead photo
            print(f"skip {record['image_id']}: {type(e).__name__}")
            continue
        records.append(record)
    return records


def write_manifest(name, records):
    MANIFEST_DIR.mkdir(parents=True, exist_ok=True)
    path = MANIFEST_DIR / f"{name}.jsonl"
    with path.open("w") as f:
        for r in records:
            f.write(json.dumps(r) + "\n")
    print(f"{path}: {len(records)} images")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--n", type=int, default=100, help="images per dataset")
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--only", choices=["mmfood", "nutrition5k"], help="prepare one dataset")
    args = parser.parse_args()

    if args.only in (None, "mmfood"):
        write_manifest("mmfood", prepare_mmfood(args.n, args.seed))
    if args.only in (None, "nutrition5k"):
        write_manifest("nutrition5k", prepare_nutrition5k(args.n, args.seed))


if __name__ == "__main__":
    sys.exit(main())